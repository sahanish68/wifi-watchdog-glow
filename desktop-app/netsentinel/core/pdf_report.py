"""PDF report export using ReportLab."""
from __future__ import annotations
import time
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import cm
from reportlab.platypus import (SimpleDocTemplate, Paragraph, Spacer, Table,
                                TableStyle, PageBreak)

NEON = colors.HexColor("#00d4ff")
DARK = colors.HexColor("#0b0f14")


def export(path: str | Path, sections: list[tuple[str, list[list[str]]]],
           title: str = "NetSentinel Report") -> str:
    path = str(path)
    doc = SimpleDocTemplate(path, pagesize=A4,
                            leftMargin=1.5*cm, rightMargin=1.5*cm,
                            topMargin=1.5*cm, bottomMargin=1.5*cm)
    styles = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=styles["Title"], textColor=NEON, fontSize=22)
    h2 = ParagraphStyle("h2", parent=styles["Heading2"], textColor=DARK, fontSize=14)
    body = styles["BodyText"]

    story = [Paragraph(title, h1),
             Paragraph(time.strftime("%Y-%m-%d %H:%M:%S"), body),
             Spacer(1, 0.5*cm)]

    for name, rows in sections:
        story.append(Paragraph(name, h2))
        if not rows:
            story.append(Paragraph("<i>No data.</i>", body))
        else:
            t = Table(rows, repeatRows=1, hAlign="LEFT")
            t.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), NEON),
                ("TEXTCOLOR",  (0, 0), (-1, 0), colors.white),
                ("FONTNAME",   (0, 0), (-1, 0), "Helvetica-Bold"),
                ("GRID",       (0, 0), (-1, -1), 0.3, colors.grey),
                ("FONTSIZE",   (0, 0), (-1, -1), 9),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1),
                 [colors.whitesmoke, colors.white]),
            ]))
            story.append(t)
        story.append(Spacer(1, 0.4*cm))

    story.append(PageBreak())
    story.append(Paragraph(
        "<i>Generated by NetSentinel — for authorized defensive auditing only.</i>",
        body))
    doc.build(story)
    return path
